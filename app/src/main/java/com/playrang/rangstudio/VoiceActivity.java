        status.setTextColor(Ui.SAFFRON_DARK);
        status.setPadding(dp(12), 0, 0, 0);
        top.addView(status, new LinearLayout.LayoutParams(0, ViewGroup.LayoutParams.WRAP_CONTENT, 1f));
